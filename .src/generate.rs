//! A Work Process unit generated from a [`Program`]: the Rust crate a
//! design compiles into, built into a library a node loads through the C
//! ABI (ADR-0066 clause 4), and the module entry that names it in the
//! cluster's configuration.
//!
//! The crate carries the program in its binary form and exports it with
//! [`crate::export_work_process!`]; it holds no code of the design's own,
//! so building it is building Xmip's engine with one program inside. Its
//! manifest says the unit works offline (the owner, 2026-10-22: *We can
//! only use standards, code and compiled units that explicitly work
//! offline!*), which is true of everything it is made of.

use std::fmt::Write as _;

use crate::form;
use crate::program::Program;

/// Where the generated crate finds `xmip-core-process`.
const PROCESS: &str = "https://github.com/IlleNilsson/xmip-core-process";

/// Where a unit came from and what it is called.
#[derive(Clone, Copy, Debug)]
pub struct Origin<'a> {
    /// The design's file, as the developer named it.
    pub design: &'a str,
    /// The format it was read as.
    pub format: &'a str,
    /// The module's name: its `[[modules]]` entry and its crate's.
    pub module: &'a str,
    /// The module's version.
    pub version: (u32, u32, u32),
}

/// A generated unit: its crate's two files and its module entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Generated {
    /// `Cargo.toml`.
    pub cargo: String,
    /// `src/lib.rs`.
    pub library: String,
    /// The `[[modules]]` entry declaring it, for the cluster's `xmip.toml`.
    pub module: String,
}

/// The unit `program` compiles into.
#[must_use]
pub fn unit(program: &Program, origin: &Origin<'_>) -> Generated {
    Generated {
        cargo: cargo(origin),
        library: library(program, origin),
        module: module(program, origin),
    }
}

/// The crate's name: the module's, as cargo spells a crate.
#[must_use]
pub fn crate_name(module: &str) -> String {
    module
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect()
}

/// The library file cargo builds the crate into, on this machine's system.
#[must_use]
pub fn library_file(module: &str) -> String {
    let stem = crate_name(module).replace('-', "_");
    if cfg!(windows) {
        format!("{stem}.dll")
    } else if cfg!(target_os = "macos") {
        format!("lib{stem}.dylib")
    } else {
        format!("lib{stem}.so")
    }
}

fn cargo(origin: &Origin<'_>) -> String {
    let (major, minor, patch) = origin.version;
    format!(
        "# Generated by Xmip from {design}, a {format} design. Compile the design again\n\
         # rather than edit this file.\n\
         [workspace]\n\n\
         [package]\n\
         name = \"{name}\"\n\
         version = \"{major}.{minor}.{patch}\"\n\
         edition = \"2024\"\n\
         publish = false\n\n\
         [lib]\n\
         crate-type = [\"cdylib\"]\n\
         path = \"src/lib.rs\"\n\n\
         [dependencies]\n\
         process = {{ package = \"xmip-core-process\", git = \"{PROCESS}\", branch = \"main\" }}\n",
        design = origin.design,
        format = origin.format,
        name = crate_name(origin.module),
    )
}

fn library(program: &Program, origin: &Origin<'_>) -> String {
    let bytes = form::program(program);
    let mut text = format!(
        "//! The Work Process '{name}', generated by Xmip from {design}, a {format}\n\
         //! design: its compiled program, exported as a Work Process unit\n\
         //! (`xmip_module.h` section 13). Compile the design again rather than\n\
         //! edit this file.\n\n\
         const PROGRAM: &[u8] = &[\n",
        name = program.name,
        design = origin.design,
        format = origin.format,
    );
    for line in bytes.chunks(16) {
        let numbers: Vec<String> = line.iter().map(u8::to_string).collect();
        let _ = writeln!(text, "    {},", numbers.join(", "));
    }
    let (major, minor, patch) = origin.version;
    let _ = write!(
        text,
        "];\n\n\
         process::export_work_process!(\n    \
         PROGRAM,\n    \
         unit = \"{unit}\",\n    \
         version = ({major}, {minor}, {patch})\n\
         );\n",
        unit = program.name,
    );
    text
}

fn module(program: &Program, origin: &Origin<'_>) -> String {
    let (major, minor, patch) = origin.version;
    format!(
        "[[modules]]\n\
         name = \"{module}\"\n\
         start = true\n\n\
         [modules.manifest]\n\
         offline = true\n\n\
         [modules.manifest.identity]\n\
         name = \"{module}\"\n\
         version = \"{major}.{minor}.{patch}\"\n\n\
         [[modules.manifest.capabilities]]\n\
         capability = \"work-process\"\n\
         execution_host = \"native-rust\"\n\
         trusted_required = false\n\n\
         [modules.manifest.entrypoint]\n\
         library_path = \"{library}\"\n\
         symbol = \"xmip_create_module_v1\"\n\n\
         [[modules.manifest.units]]\n\
         name = \"{unit}\"\n\
         capability = \"work-process\"\n\
         stages = [\"process\"]\n\
         offline = true\n",
        module = origin.module,
        library = library_file(origin.module),
        unit = program.name,
    )
}
